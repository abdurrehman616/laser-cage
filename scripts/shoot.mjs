import { chromium } from 'playwright-core';
const out = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const pg = await b.newPage({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
const errs = [];
pg.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()); });
pg.on('pageerror', e => errs.push('pageerror: ' + e.message));
await pg.goto('http://localhost:4173/'); await pg.waitForTimeout(1500);
await pg.screenshot({ path: out + '/1-home.png' });
await pg.click('#shopBtn'); await pg.waitForTimeout(400);
await pg.click('.itm:nth-child(7)'); await pg.waitForTimeout(500);
await pg.screenshot({ path: out + '/2-shop.png' });
await pg.click('#shop .back');
await pg.click('.mode[data-mode=bots]'); await pg.waitForTimeout(300);
await pg.screenshot({ path: out + '/3-setup.png' });
await pg.click('#playBtn'); await pg.waitForTimeout(300);
await pg.screenshot({ path: out + '/4-howto.png' });
await pg.click('#howOk'); await pg.waitForTimeout(700);
await pg.screenshot({ path: out + '/5-intro.png' });
await pg.waitForFunction(() => window.__lc.match?.phase === 'hide');
await pg.mouse.click(260, 520); await pg.waitForTimeout(1200);
await pg.screenshot({ path: out + '/6-hide.png' });
await pg.waitForFunction(() => window.__lc.match?.phase === 'lock', null, { timeout: 60000 });
await pg.waitForTimeout(300);
await pg.screenshot({ path: out + '/7-lock.png' });
await pg.waitForFunction(() => window.__lc.match?.phase === 'fire', null, { timeout: 30000 });
await pg.waitForTimeout(150);
await pg.screenshot({ path: out + '/8-fire.png' });
await pg.waitForFunction(() => ['drop','over'].includes(window.__lc.match?.phase), null, { timeout: 30000 });
await pg.waitForTimeout(500);
await pg.screenshot({ path: out + '/9-drop.png' });
const st = await pg.evaluate(() => ({ phase: window.__lc.match?.phase, round: window.__lc.match?.round, alive: window.__lc.match?.alive.length }));
console.log(JSON.stringify(st));
await pg.waitForSelector('#result:not([hidden])', { timeout: 90000 }).catch(() => console.log('no result yet'));
await pg.waitForTimeout(400);
await pg.screenshot({ path: out + '/10-result.png' });
// pass & play
await pg.click('#homeBtn'); await pg.click('.mode[data-mode=pp]'); await pg.click('#playBtn');
await pg.waitForSelector('#handoff:not([hidden])', { timeout: 30000 });
await pg.screenshot({ path: out + '/11-handoff.png' });
await pg.click('#readyBtn'); await pg.waitForTimeout(400);
await pg.mouse.click(230, 560); await pg.waitForTimeout(300);
await pg.screenshot({ path: out + '/12-plan.png' });
console.log(errs.slice(0, 15).join('\n') || 'no console errors');
await b.close();
