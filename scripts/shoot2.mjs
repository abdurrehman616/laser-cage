import { chromium } from 'playwright-core';
const out = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const pg = await b.newPage({ viewport: { width: 400, height: 860 }, hasTouch: true, isMobile: true });
const errs = []; pg.on('pageerror', e => errs.push(e.message)); pg.on('console', m => m.type() === 'error' && errs.push(m.text()));
await pg.goto('http://localhost:4173/'); await pg.waitForTimeout(1500);
await pg.screenshot({ path: out + '/a-home.png' });
await pg.click('#shopBtn'); await pg.waitForTimeout(300); await pg.click('.itm:nth-child(5)'); await pg.waitForTimeout(800);
await pg.screenshot({ path: out + '/b-shop.png' });
await pg.click('#shop .back'); await pg.click('#settingsBtn'); await pg.waitForTimeout(300);
await pg.screenshot({ path: out + '/c-settings.png' });
await pg.click('#settings .back'); await pg.click('#playBtn'); await pg.waitForTimeout(300);
await pg.screenshot({ path: out + '/d-howto.png' });
await pg.click('#howOk'); await pg.waitForTimeout(500);
await pg.screenshot({ path: out + '/e-intro.png' });
await pg.waitForFunction(() => window.__lc.match?.phase === 'hide', null, { timeout: 30000 }); await pg.waitForTimeout(400);
await pg.screenshot({ path: out + '/f-hide.png' });
await pg.waitForFunction(() => window.__lc.match?.phase === 'lock', null, { timeout: 30000 }); await pg.waitForTimeout(250);
await pg.screenshot({ path: out + '/g-lock.png' });
await pg.waitForSelector('#result:not([hidden])', { timeout: 120000 }); await pg.waitForTimeout(500);
await pg.screenshot({ path: out + '/h-result.png' });
console.log(errs.join('\n') || 'no errors'); await b.close();
