import { chromium } from 'playwright-core';
const out = process.argv[2];
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const pg = await b.newPage({ viewport: { width: 360, height: 640 }, deviceScaleFactor: 3, hasTouch: true, isMobile: true });
await pg.goto('http://localhost:4173/'); await pg.waitForTimeout(800);
await pg.evaluate(() => { const p = window.__lc.profile; p.tutorialDone = true; p.gfx = 'high'; p.coins = 1240; });
await pg.reload(); await pg.waitForTimeout(400);
await pg.evaluate(() => { const p = window.__lc.profile; p.tutorialDone = true; p.coins = 1240; });
await pg.click('#shopBtn'); await pg.click('#shop .back'); await pg.waitForTimeout(1800);
await pg.screenshot({ path: out + '/2-home.png' });
await pg.click('#shopBtn'); await pg.waitForTimeout(300); await pg.click('#shopTabs button:nth-child(2)'); await pg.click('.itm:nth-child(4)'); await pg.waitForTimeout(1800);
await pg.screenshot({ path: out + '/4-shop.png' });
await pg.click('#shop .back');
await pg.evaluate(() => { window.__lc.setup.bots = 5; });
await pg.click('#playBtn');
await pg.waitForFunction(() => window.__lc.match?.phase === 'intro'); await pg.waitForTimeout(500);
await pg.screenshot({ path: out + '/1-round.png' });
await pg.waitForFunction(() => window.__lc.match?.phase === 'hide', null, { timeout: 30000 });
const mv = await pg.locator('#movepad').boundingBox();
await pg.mouse.move(mv.x + mv.width / 2, mv.y + mv.height / 2); await pg.mouse.down(); await pg.mouse.move(mv.x + mv.width / 2 + 30, mv.y + mv.height / 2 - 35);
await pg.waitForTimeout(900);
await pg.screenshot({ path: out + '/3-hide.png' });
await pg.mouse.up();
await pg.waitForFunction(() => window.__lc.match?.phase === 'lock', null, { timeout: 30000 }); await pg.waitForTimeout(300);
await pg.screenshot({ path: out + '/5-lock.png' });
await b.close();
